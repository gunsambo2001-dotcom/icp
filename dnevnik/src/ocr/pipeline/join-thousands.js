// Склеивает разорванный пробелом-разделителем тысяч номер обратно в одно
// число ДО того, как decimal-anchor.js/magnitude-anchor.js ищут по
// полнотекстовому OCR числа-ориентиры.
//
// НАХОДКА НА РЕАЛЬНОМ ТЕЛЕФОННОМ СКРИНШОТЕ (BTC, шкала цены «79 250,0»):
// Tesseract на более шумном/сжатом фото не всегда отбрасывает
// пробел-разделитель тысяч чисто — либо оставляет его как есть («79
// 250,0»), либо (чаще на этой фотографии) принимает его за точку: «79
// 000,0» → «79.000,0». Второй случай выглядит как самостоятельное число
// с 3 «знаками после запятой» и портит якорь: часть меток на скриншоте
// «согласны» на 1 знак, часть — на 3, расхождение → якорь сбрасывается в
// null → честные 5-6-значные Entry/Stop/Target отбрасываются целиком (нет
// якоря — не гадаем), а мусорные короткие обрывки (обрезки текста осей)
// остаются единственными кандидатами.
//
// Исправляем ДО якорей, а не подгонкой порога в самих якорях: это не
// эвристика вероятности, а прямая реконструкция — «79.000,0» с последующей
// запятой И ТРЕМЯ нулями после точки почти наверняка означает разделитель
// тысяч, а не десятичную часть (у цен с реальными 3 знаками после запятой
// после «.000» никогда не идёт ещё один разделитель+цифры).
export function joinThousandsSpaces(fullText) {
  return fullText
    // настоящий пробел (обычный/неразрывный) как разделитель тысяч
    .replace(/(\d{1,3})[  ](\d{3})(?=[.,]\d)/g, '$1$2')
    // пробел, ошибочно распознанный как точка (потом идёт настоящий
    // разделитель — запятая/точка — с цифрами: значит первая точка не десятичная)
    .replace(/(\d{1,3})\.(\d{3})(?=[.,]\d)/g, '$1$2');
}
