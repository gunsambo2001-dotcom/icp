// Крошечные DOM-помощники. Не фреймворк — просто чтобы не писать document.createElement руками.

/**
 * h('div.card', { onclick }, [child, 'text'])  →  HTMLElement
 * Тег + классы через точку. Атрибуты: className/class, dataset (data-*), on* — слушатели,
 * html — innerHTML (осторожно), остальное — setAttribute.
 */
export function h(spec, props = {}, children = []) {
  const [tag, ...cls] = spec.split('.');
  const el = document.createElement(tag || 'div');
  if (cls.length) el.className = cls.join(' ');

  for (const [k, v] of Object.entries(props || {})) {
    if (v == null || v === false) continue;
    if (k === 'class' || k === 'className') el.className = [el.className, v].filter(Boolean).join(' ');
    else if (k === 'html') el.innerHTML = v;
    else if (k === 'text') el.textContent = v;
    else if (k === 'dataset') Object.assign(el.dataset, v);
    else if (k.startsWith('on') && typeof v === 'function') el.addEventListener(k.slice(2), v);
    else if (k === 'disabled' || k === 'checked' || k === 'selected' || k === 'hidden') el[k] = !!v;
    else el.setAttribute(k, v);
  }

  for (const c of [].concat(children)) {
    if (c == null || c === false) continue;
    el.append(c instanceof Node ? c : document.createTextNode(String(c)));
  }
  return el;
}

/**
 * Экранирует значение для вставки в innerHTML/атрибут. Наставник открывает данные, введённые
 * учениками, — им нельзя доверять: любой текст из сделки в html-строку только через esc().
 */
export function esc(v) {
  return String(v ?? '').replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]);
}

/**
 * Ссылка, введённая пользователем → безопасный http(s)-адрес или null. Без схемы дописывает https://
 * («tradingview.com/x/abc» → «https://tradingview.com/x/abc»); javascript:, data: и мусор без точки в хосте отклоняет.
 */
export function safeHttpUrl(raw) {
  const text = String(raw ?? '').trim();
  if (!text) return null;
  const withScheme = /^[a-z][a-z0-9+.-]*:/i.test(text) ? text : 'https://' + text;
  try {
    const url = new URL(withScheme);
    return (url.protocol === 'https:' || url.protocol === 'http:') && url.hostname.includes('.') ? url.href : null;
  } catch {
    return null;
  }
}

/** Заменить содержимое узла. */
export function mount(host, ...nodes) {
  host.replaceChildren(...nodes.flat().filter(Boolean));
}

export function svgIcon(paths, size = 16) {
  return `<svg viewBox="0 0 24 24" width="${size}" height="${size}" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${paths}</svg>`;
}

